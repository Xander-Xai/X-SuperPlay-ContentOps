#!/usr/bin/env python3
"""Emit each account's ``easel.yaml`` from its DNA.

The one-click prompt asks for an Easel config alongside the storyboard. The DNA
is the source of truth, so this file is generated, never hand-edited: a hand
edited yaml would be a second set of colour and canvas values that could drift
from the DNA the pipeline actually reads.

Written with the standard library only — the output is a flat, deterministic
YAML subset (scalars, nested maps, string lists), which is all Easel needs.

Usage
-----
```
python scripts/export_easel_yaml.py
python scripts/export_easel_yaml.py --check   # fail if a file is stale
```
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, List

ROOT = Path(__file__).resolve().parents[1]
ACCOUNTS = ROOT / "config" / "accounts"


def _scalar(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    text = str(value)
    if text == "" or any(ch in text for ch in ":#[]{}\n\"'"):
        return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return text


def _emit(value: Any, indent: int = 0) -> List[str]:
    pad = "  " * indent
    lines: List[str] = []
    if isinstance(value, dict):
        for key, item in value.items():
            if isinstance(item, (dict, list)) and item:
                lines.append(f"{pad}{key}:")
                lines.extend(_emit(item, indent + 1))
            else:
                lines.append(f"{pad}{key}: {_scalar(item)}")
    elif isinstance(value, list):
        for item in value:
            if isinstance(item, dict):
                inner = _emit(item, indent + 1)
                if inner:
                    inner[0] = f"{pad}- " + inner[0].lstrip()
                lines.extend(inner)
            elif isinstance(item, list):
                lines.append(f"{pad}-")
                lines.extend(_emit(item, indent + 1))
            else:
                lines.append(f"{pad}- {_scalar(item)}")
    else:
        lines.append(f"{pad}{_scalar(value)}")
    return lines


def build(dna: dict) -> str:
    render = dna["render"]
    palette = dna["brand"]["palette"]
    caption = dna["visual"]["caption_style"]
    audio = render["audio"]
    canvas = render["canvas"]

    payload = {
        "schema": "contentops.easel-profile/v1",
        "generated_from": f"config/accounts/{dna['slug']}.json",
        "generated_note": "Generated from the account DNA. Edit the DNA, not this file.",
        "account": dna["account"],
        "slug": dna["slug"],
        "role": dna["role"],
        "canvas": {
            "width": canvas["width"],
            "height": canvas["height"],
            "orientation": canvas["orientation"],
            "fps": render.get("fps", 30),
        },
        "fonts": render["fonts"],
        "colors": {
            "base": palette["base"],
            "accent": palette["accent"],
            "ink": palette["ink"],
            "muted": palette["muted"],
            "surface": palette["surface"],
            "problem": palette.get("problem", "#F07167"),
            "code_theme": palette.get("code_theme", "monokai-dark"),
        },
        "captions": {
            "font": caption["font"],
            "size_px": caption["size_px"],
            "max_chars_per_line": caption["max_chars_per_line"],
            "density": caption.get("density", "sparse"),
            "highlight": caption["highlight"],
            "outline": caption["outline"],
            "shadow": caption["shadow"],
            "burn_style": caption["burn_style"],
            "safe_zone": caption["safe_zone"],
        },
        "audio": {
            "voice_provider": audio["voice_provider"],
            "sample_rate": audio.get("sample_rate", 32000),
            "channels": audio.get("channels", 1),
            "bgm": audio.get("bgm", "OMITTED_BY_POLICY"),
            "bgm_max_db_below_voice": dna["audio"]["bgm"]["max_db_below_voice"],
        },
        "composition": dna["visual"]["composition"],
        "qc": {
            "checks": render["qc_checks"],
            "cover_whitespace_min_ratio": dna["visual"]["cover"]["whitespace_min_ratio"],
            "cover_title_lines": dna["visual"]["cover"]["title_lines"],
            "real_source_ratio_min": 0.70,
        },
        "evidence": {
            "manual_recording": dna["evidence"]["manual_recording"],
            "required_evidence_class": dna["evidence"]["required_evidence_class"],
        },
        "engine": render.get("engine", "easel"),
        "runtime_pin": render.get("runtime_pin", ""),
        "production_ready": False,
        "human_review": "PENDING_FOUNDER_REVIEW",
    }
    header = (
        "# Generated by scripts/export_easel_yaml.py from the account DNA.\n"
        "# Do not edit by hand: the DNA is the source of truth.\n"
    )
    return header + "\n".join(_emit(payload)) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if any emitted file differs from what is on disk")
    args = parser.parse_args()

    stale = []
    written = []
    for dna_path in sorted(ACCOUNTS.glob("*.json")):
        dna = json.loads(dna_path.read_text(encoding="utf-8"))
        text = build(dna)
        target = ROOT / "projects" / dna["slug"] / "easel.yaml"
        if args.check:
            existing = target.read_text(encoding="utf-8") if target.is_file() else ""
            if existing != text:
                stale.append(target.relative_to(ROOT).as_posix())
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        written.append(target.relative_to(ROOT).as_posix())

    if args.check:
        if stale:
            print("STALE easel.yaml (re-run scripts/export_easel_yaml.py):")
            for item in stale:
                print(f"  {item}")
            return 1
        print("[easel_yaml] PASS — every easel.yaml matches its DNA")
        return 0

    for item in written:
        print(f"wrote {item}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
