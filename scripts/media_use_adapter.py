def cmd_status(args: argparse.Namespace) -> int:
    return _emit(_ok({"status": _adapter(args).status().as_dict()}), EXIT_OK)


def cmd_doctor(args: argparse.Namespace) -> int:
    doctor = _adapter(args).doctor()
    payload = _ok({"doctor": doctor.as_dict()})
    # A failed dependency check is a diagnosis, not a crash. It still means a
    # human must act before the affected provider can run.
    return _emit(payload, EXIT_OK if doctor.ok else EXIT_BLOCKED)


def cmd_candidates(args: argparse.Namespace) -> int:
    rows = _adapter(args).candidates(
        args.type,
        project_dir=_project(args),
        intent=args.intent or "",
        consult_global_cache=bool(args.global_cache),
    )
    if args.global_cache and not args.allow_cross_project:
        raise MediaUseError(
            CODE_CROSS_PROJECT_NOT_AUTHORIZED,
            "--global-cache lists another project's material; pass "
            "--allow-cross-project to acknowledge that this is cross-project reuse.",
        )
    return _emit(_ok({"type": args.type, "candidates": [r.as_dict() for r in rows]}), EXIT_OK)


def cmd_resolve(args: argparse.Namespace) -> int:
    resolution = _adapter(args).resolve(
        args.type,
        args.intent or "",
        project_dir=_project(args),
        authorization=_authorization(args),
        provider=args.provider,
    )
    payload = _ok({"resolution": resolution.as_dict()})
    return _emit(payload, EXIT_OK if resolution.importable else EXIT_BLOCKED)


def cmd_adopt(args: argparse.Namespace) -> int:
    rows = _adapter(args).adopt(project_dir=_project(args))
    return _emit(_ok({"adopted": rows, "count": len(rows)}), EXIT_OK)


def cmd_ingest(args: argparse.Namespace) -> int:
    project_dir = _project(args)
    # Same policy as ``import``: copying a file into the project is a direct
    # material import, so choosing this verb must not be a way around the gate.
    _import_rights(project_dir, args.license or "",
                   getattr(args, "rights_review", "") or "",
                   args.attribution or "", False)
    record = _adapter(args).ingest(
        args.type,
        Path(args.source).expanduser(),
        project_dir=project_dir,
        license=args.license,
        attribution=args.attribution or "",
    )
    return _emit(_ok({"record": record}), EXIT_OK)


def _import_rights(project_dir: Path, license_name: str, review: str,
                   attribution: str, synthetic: bool) -> Optional[Dict[str, Any]]:
    """Return the rights block a third-party import must carry.

    Owned licences keep their existing semantics and need no sidecar. A
    third-party licence must point at a review record inside the project, and
    that record is validated by the same gate the M5 chain uses.
    """
    try:
        policy = license_policy(license_name)
    except RightsError as exc:
        raise MediaUseError(CODE_RIGHTS_REVIEW_REQUIRED, str(exc)) from exc
    if not policy["third_party"]:
        return None
    if not review:
        raise MediaUseError(
            CODE_RIGHTS_REVIEW_REQUIRED,
            "a third-party import needs --rights-review pointing at "
            "assets/<id>.rights.json")
    path = Path(review)
    if not path.is_absolute():
        path = project_dir / path
    try:
        relative = path.resolve().relative_to(project_dir.resolve()).as_posix()
        record = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise MediaUseError(
            CODE_RIGHTS_REVIEW_REQUIRED,
            f"the rights review cannot be read inside the project: {exc}") from exc
    block = {
        "schema": "contentops.media-rights/v1",
        "license_id": str(record.get("license_id") or license_name),
        "source_url": str(record.get("source_url") or ""),
        "reviewed_by": str(record.get("reviewed_by") or ""),
        "reviewed_at": str(record.get("reviewed_at") or ""),
        "review_evidence": relative,
        "attribution": attribution or str(record.get("attribution") or ""),
        "synthetic": bool(record.get("synthetic", synthetic)),
    }
    try:
        validate_declared_asset(
            {"permission": "LICENSED", "license": license_name, "rights": block},
            project_dir,
        )
    except RightsError as exc:
        raise MediaUseError(CODE_RIGHTS_REVIEW_REQUIRED, str(exc)) from exc
    return block


def cmd_import(args: argparse.Namespace) -> int:
    project_dir = _project(args)
    _import_rights(project_dir, args.license or "", args.rights_review or "",
                   args.attribution or "", bool(args.synthetic))
    record = (
        _find_record(project_dir, args.record_id)
        if args.record_id
        else _read_json(args.record_file)
    )
    imported = _adapter(args).import_record(
        record,
        project_dir=project_dir,
        kind=args.type,
        license=args.license or "",
        attribution=args.attribution or "",
        role=args.role,
        placement_id=args.placement,
        asset_id_prefix=args.asset_prefix,
        cross_project=bool(args.cross_project),
    )
    return _emit(_ok({"imported": imported.as_dict()}), EXIT_OK)


def cmd_verify(args: argparse.Namespace) -> int:
    result = _adapter(args).verify(
        project_dir=_project(args),
        relative_path=args.path,
        expected_sha256=args.sha256,
    )
    return _emit(_ok({"verification": result.as_dict()}), EXIT_OK if result.ok else EXIT_BLOCKED)


