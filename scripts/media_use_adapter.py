def _adapter(args: argparse.Namespace) -> MediaUseAdapter:
    return MediaUseAdapter(
        skill_dir=Path(args.skill_dir) if args.skill_dir else None,
        node=args.node,
        timeout=float(args.timeout),
    )


def _authorization(args: argparse.Namespace) -> MediaUseAuthorization:
    return MediaUseAuthorization(
        allow_network=bool(getattr(args, "allow_network", False)),
        allow_paid=bool(getattr(args, "allow_paid", False)),
        paid_budget=getattr(args, "budget", None),
        allow_cross_project_reuse=bool(getattr(args, "allow_cross_project", False)),
        allowed_providers=tuple(getattr(args, "allowed_provider", None) or ()),
    )


def _project(args: argparse.Namespace) -> Path:
    path = Path(args.project).expanduser()
    return path if path.is_absolute() else (ROOT / path)


def _read_jsonl(path: Path) -> List[Dict[str, Any]]:
    """Read media-use's own inventory. Never a second asset list of our making."""
    if not path.is_file():
        return []
    records: List[Dict[str, Any]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            item = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(item, dict):
            records.append(item)
    return records


def _find_record(project_dir: Path, record_id: str) -> Dict[str, Any]:
    records = _read_jsonl(project_dir / ".media" / "manifest.jsonl")
    for record in reversed(records):
        if str(record.get("id")) == record_id:
            return record
    raise MediaUseError(
        CODE_CLI_FAILED,
        f"no media-use record with id {record_id!r} in {project_dir / '.media' / 'manifest.jsonl'}. "
        f"Run `adopt` or `resolve` first; this command never invents a record.",
        details={"record_id": record_id},
    )


def _write_json(path: Path, payload: Mapping[str, Any]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return path


def _read_json(path: str) -> Dict[str, Any]:
    payload = json.loads(Path(path).expanduser().read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise MediaUseError(
            CODE_CLI_FAILED, f"{path} does not contain a JSON object"
        )
    return payload


