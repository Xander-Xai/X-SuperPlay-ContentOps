def _ffmpeg() -> Optional[str]:
    return shutil.which("ffmpeg")


def _make_png(path: Path, *, size: str, colour: str) -> None:
    from process_utils import hidden_run

    ffmpeg = _ffmpeg()
    if not ffmpeg:
        raise MediaUseError(CODE_NEEDS_HUMAN_ACTION, "ffmpeg is not installed")
    path.parent.mkdir(parents=True, exist_ok=True)
    proc = hidden_run(
        [
            ffmpeg,
            "-hide_banner",
            "-loglevel",
            "error",
            "-f",
            "lavfi",
            "-i",
            f"color=c={colour}:s={size}:d=1",
            "-frames:v",
            "1",
            "-fflags",
            "+bitexact",
            "-flags:v",
            "+bitexact",
            "-y",
            str(path),
        ],
        timeout=60,
    )
    if proc.returncode != 0 or not path.is_file():
        raise MediaUseError(
            CODE_CLI_FAILED,
            f"ffmpeg could not draw the demo fixture: {redact_text(proc.stderr[:400])}",
        )


def _make_svg_icon(path: Path) -> None:
    """A deterministic SVG icon, so media-use's ``icon`` inference is exercised."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">'
        '<rect width="64" height="64" rx="12" fill="#1f6feb"/>'
        '<path d="M18 40 L32 16 L46 40 Z" fill="#ffffff"/>'
        "</svg>\n",
        encoding="utf-8",
    )


def _make_bgm(path: Path, *, seconds: float = 6.0, rate: int = 44100) -> None:
    """Deterministic two-tone bed. stdlib only, so the demo has no extra dependency."""
    path.parent.mkdir(parents=True, exist_ok=True)
    frames = int(seconds * rate)
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(rate)
        samples = bytearray()
        for index in range(frames):
            t = index / rate
            # A slow crossfade between two sine tones; no randomness, so two runs
            # on the same Python produce identical bytes.
            value = 0.18 * math.sin(2 * math.pi * 220.0 * t) + 0.12 * math.sin(
                2 * math.pi * 277.18 * t
            )
            value *= min(1.0, index / (rate * 0.25), (frames - index) / (rate * 0.25))
            samples += struct.pack("<h", int(value * 32767))
        handle.writeframes(bytes(samples))


def _real_screenshot(project_dir: Path, source: Path, name: str) -> Optional[Path]:
    if not source.is_file():
        return None
    target = project_dir / "sources" / "screenshots" / name
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)
    return target


def _real_envelope(
    project_dir: Path,
    path: Path,
    *,
    asset_id: str,
    placement_id: str,
    claim_ref: str,
) -> MediaAssetEnvelope:
    """Register a genuine capture.

    The receipt is the same ``contentops.media-import/v1`` shape a licensed
    import uses, because a screenshot is also material no provider produced. The
    difference is in the *envelope*: ``SCREENSHOT`` is evidence-capable, and the
    role is ``UI_SCREENSHOT``, which is what makes this asset able to carry the
    claim rather than merely decorate it.
    """
    digest = sha256_file(path)
    relative = path.relative_to(project_dir).as_posix()
    receipt_path = path.with_name(path.name + ".receipt.json")
    receipt = {
        "schema": IMPORT_SCHEMA,
        "record_type": "media_import",
        "provider": "local_capture",
        "product": "contentops",
        "transport": "operator_capture",
        "asset_id": asset_id,
        "modality": MediaModality.IMAGE,
        "imported_kind": AssetKind.SCREENSHOT,
        "source_type": "operator_screenshot",
        "source_uri": f"project://{relative}",
        "project_relative_path": relative,
        "output_sha256": digest,
        "bytes": path.stat().st_size,
        "fingerprint": import_fingerprint(AssetKind.SCREENSHOT, digest),
        "license": "OWNED (captured by the ContentOps operator)",
        "attribution": "",
        "generated": False,
        "evidence_capable": True,
        "provider_call": False,
        "production_ready": False,
        "human_review": HUMAN_REVIEW_PENDING,
        "note": "A real capture from this repository's own Easel review. It may be "
        "used as UI evidence; it has not been approved by a human yet.",
    }
    _write_json(receipt_path, receipt)
    return MediaAssetEnvelope(
        asset_id=asset_id,
        modality=MediaModality.IMAGE,
        placement_id=placement_id,
        path="project://" + relative,
        sha256=digest,
        receipt_ref=receipt_path.name,
        fingerprint=receipt["fingerprint"],
        asset_kind=AssetKind.SCREENSHOT,
        generated=False,
        evidence_capable=True,
        evidence_use=EvidenceUse.UI_SCREENSHOT,
        claim_refs=[claim_ref],
        technical_status=TECHNICAL_NOT_RUN,
        human_review=HUMAN_REVIEW_PENDING,
        production_ready=False,
    )


def _decision_row(decision: GateDecision) -> Dict[str, Any]:
    return decision.as_dict()


def cmd_demo(args: argparse.Namespace) -> int:
    """Run the whole offline path and write a receipt for every stage.

    What this proves: discovery, offline catalog reuse, adoption, licensed
    import, the evidence boundary, manifest determinism, storyboard translation,
    composition and final QC.

    What it does not prove: that a stock image can be fetched. That needs a
    network authorization this run does not have, and the demo records the
    refusal instead of pretending otherwise.
    """
    project_dir = _project(args)
    project_dir.mkdir(parents=True, exist_ok=True)
    adapter = _adapter(args)
    steps: Dict[str, Any] = {}
    limitations: List[str] = []
    report: Dict[str, Any] = {
        "schema": "contentops.media-use-demo/v1",
        "project": project_dir.relative_to(ROOT).as_posix()
        if project_dir.is_relative_to(ROOT)
        else project_dir.name,
        "production_ready": False,
        "steps": steps,
        "limitations": limitations,
    }

    status = adapter.status()
    steps["status"] = {"state": "PASS" if status.available else "BLOCKED", **status.as_dict()}
    if not status.available:
        report["limitations"].append("the media-use skill is not usable here: " + "; ".join(status.reasons))
        _write_json(project_dir / "receipts" / "media-use-demo.json", report)
        return _emit(report, EXIT_BLOCKED)

    # -- offline catalog reuse, and the refusal that proves fail-closed ------
    sfx_record: Optional[Dict[str, Any]] = None
    try:
        sfx = adapter.resolve(
            "sfx",
            "soft ui transition chime",
            project_dir=project_dir,
            authorization=MediaUseAuthorization(),
        )
        sfx_record = dict(sfx.record)
        steps["resolve_sfx"] = {
            "state": "PASS" if sfx.importable else "BLOCKED",
            "source": sfx.source,
            "importable": sfx.importable,
            "record": sfx.record,
        }
    except MediaUseError as exc:
        steps["resolve_sfx"] = {"state": "BLOCKED", **exc.as_dict()}

    # An image with no local candidate and no network authorization must not
    # quietly reach a provider. This is the check, recorded rather than assumed.
    empty_project = project_dir / ".demo-empty"
    empty_project.mkdir(parents=True, exist_ok=True)
    try:
        refused = adapter.resolve(
            "image",
            "abstract technology background",
            project_dir=empty_project,
            authorization=MediaUseAuthorization(),
        )
        steps["resolve_image_offline"] = {
            "state": "BLOCKED" if not refused.importable else "UNEXPECTED",
            "blocked_code": refused.blocked_code,
            "blocked_reason": refused.blocked_reason,
            "importable": refused.importable,
        }
    except MediaUseError as exc:
        steps["resolve_image_offline"] = {"state": "BLOCKED", **exc.as_dict()}

    # -- demo fixtures, adopted through the skill's own inventory ------------
    assets = project_dir / "assets"
    try:
        _make_png(assets / "tech-background.png", size="1080x1920", colour="0x0b1220")
        _make_png(assets / "brand-mark.png", size="256x256", colour="0x1f6feb")
        _make_svg_icon(assets / "brand-icon.svg")
        _make_bgm(assets / "bgm" / "tech-bgm.wav")
        steps["fixtures"] = {"state": "PASS", "note": DEMO_FIXTURE_LICENSE}
    except MediaUseError as exc:
        steps["fixtures"] = {"state": "BLOCKED", **exc.as_dict()}
        limitations.append("demo fixtures could not be generated; run is partial")

    adopted: List[Dict[str, Any]] = []
    if (assets).is_dir():
        adopted = adapter.adopt(project_dir=project_dir)
    # ``adopt`` only returns *newly* registered files, so a second demo run sees
    # an empty list. The inventory is the single source of truth for what exists;
    # reading it here is what makes the demo idempotent without inventing records.
    inventory = _read_jsonl(project_dir / ".media" / "manifest.jsonl")
    steps["adopt"] = {
        "state": "PASS",
        "count": len(adopted),
        "records": inventory,
        "newly_adopted": len(adopted),
    }

    # -- licensed imports ----------------------------------------------------
    imported = []
    envelopes: List[MediaAssetEnvelope] = []
    registry = AssetRegistry()

    def _import(path_suffix: str) -> None:
        record = next(
            (
                r
                for r in reversed(inventory)
                if str(r.get("path", "")).endswith(path_suffix)
            ),
            None,
        )
        if record is None:
            return
        media = adapter.import_record(
            record,
            project_dir=project_dir,
            kind=str(record.get("type") or ""),
            license=DEMO_FIXTURE_LICENSE,
            role="visual_support",
            registry=registry,
        )
        imported.append(media.as_dict())
        envelopes.append(media.envelope)

    for suffix in ("tech-background.png", "brand-mark.png", "brand-icon.svg", "tech-bgm.wav"):
        _import(suffix)

    if sfx_record is not None and sfx_record.get("path"):
        try:
            media = adapter.import_record(
                sfx_record,
                project_dir=project_dir,
                kind="sfx",
                license=SFX_LICENSE,
                attribution=SFX_ATTRIBUTION,
                role="visual_support",
                registry=registry,
            )
            imported.append(media.as_dict())
            envelopes.append(media.envelope)
        except MediaUseError as exc:
            steps["import_sfx"] = {"state": "BLOCKED", **exc.as_dict()}

    steps["import"] = {"state": "PASS" if imported else "BLOCKED", "imported": imported}

    # -- genuine evidence ----------------------------------------------------
    real_specs = (
        (
            "sh-01",
            ROOT / "projects" / "easel-review" / "sources" / "screenshots" / "01-easel-hero.png",
            "01-easel-hero.png",
            "beat-01",
            "Easel presents a running video project",
        ),
        (
            "sh-02",
            ROOT / "projects" / "easel-review" / "sources" / "screenshots" / "02-easel-features.png",
            "02-easel-features.png",
            "beat-02",
            "Easel's feature set is visible in its own UI",
        ),
    )
    real_missing: List[str] = []
    for asset_id, source, name, placement, claim in real_specs:
        copied = _real_screenshot(project_dir, source, name)
        if copied is None:
            real_missing.append(name)
            continue
        envelopes.append(
            _real_envelope(
                project_dir,
                copied,
                asset_id=asset_id,
                placement_id=placement,
                claim_ref=claim,
            )
        )
    if real_missing:
        limitations.append(
            "these real screenshots are absent on this machine and were not fabricated: "
            + ", ".join(real_missing)
        )
    steps["real_evidence"] = {
        "state": "PASS" if len(envelopes) > len(imported) else "BLOCKED",
        "claim_refs": [e.claim_refs[0] for e in envelopes if e.claim_refs],
        "missing": real_missing,
    }

    # -- gate + manifest -----------------------------------------------------
    gate = AssetQualityGate()
    decisions = gate.evaluate_all(envelopes, repo_root=ROOT, project_root=project_dir)
    steps["gate"] = {
        "state": "PASS",
        "decisions": [_decision_row(decision) for decision in decisions],
        "admissible": [
            d.asset_id for d in decisions if d.state in ADMISSIBLE_GATE_STATES
        ],
    }

    manifest = build_manifest(
        envelopes,
        decisions,
        scheduling={},
        narration={},
        notes={
            "purpose": "media-use integration technical sample; not a production deliverable",
            "production_ready": False,
            "human_review": HUMAN_REVIEW_PENDING,
            "fixtures": DEMO_FIXTURE_LICENSE,
            "real_source_types": ["SCREENSHOT"],
        },
    )
    manifest_path = manifest.write(project_dir / "receipts" / "media-manifest.json")
    report["manifest"] = {
        "path": manifest_path.relative_to(project_dir).as_posix(),
        "fingerprint": manifest.fingerprint(),
        "assets": len(manifest.assets),
        "timeline": [placement.placement_id for placement in manifest.timeline],
    }

    # -- storyboard, composition, QC ----------------------------------------
    from m45_media_integration import manifest_to_storyboard

    storyboard = manifest_to_storyboard(
        manifest,
        narration_wav=None,
        repo_root=ROOT,
        project_root=project_dir,
        still_seconds=15.0,
        shot_motion="ken-burns",
    )
    storyboard_path = _write_json(project_dir / "script" / "storyboard.json", storyboard)
    (project_dir / "script" / "master.md").write_text(
        "# media-use integration sample\n\n"
        "Two real Easel screenshots, a licensed bundled SFX and local placeholder "
        "fixtures. This script exists so final QC can grade the sample against the "
        "same contract as a normal project; it is **not** a production script and "
        "**not** approved for publication.\n",
        encoding="utf-8",
    )
    steps["storyboard"] = {
        "state": "PASS" if storyboard.get("shots") else "BLOCKED",
        "path": storyboard_path.relative_to(project_dir).as_posix(),
        "shots": [
            {"shot_id": s.get("shot_id"), "source_type": s.get("source_type")}
            for s in storyboard.get("shots", [])
        ],
    }

    if args.skip_compose:
        steps["compose"] = {"state": "NOT_RUN", "reason": "--skip-compose"}
        steps["qc"] = {"state": "NOT_RUN", "reason": "--skip-compose"}
    elif not storyboard.get("shots"):
        steps["compose"] = {"state": "NOT_RUN", "reason": "no shots to compose"}
        steps["qc"] = {"state": "NOT_RUN", "reason": "no shots to compose"}
    else:
        try:
            from assemble_easel import run as assemble_run

            composed = assemble_run(project_dir, out_name="media-use-demo")
            steps["compose"] = {"state": composed.get("status", "PASS"), **composed}
        except Exception as exc:  # noqa: BLE001 - recorded, never silently swallowed
            steps["compose"] = {
                "state": "BLOCKED",
                "reason": redact_text(f"{type(exc).__name__}: {exc}"),
            }

        video = steps["compose"].get("video")
        if video and Path(str(video)).is_file():
            try:
                from qc_video import qc as qc_run

                runtime = dict(qc_run(project_dir, target=Path(str(video)).name))
                reasons = (
                    "fixture-assisted technical integration sample, not a production "
                    "deliverable; human review is pending"
                )
                written = write_canonical_qc_receipt(
                    project_dir,
                    runtime,
                    repo_root=ROOT,
                    name="media-use-demo-qc",
                    graded_target=Path(str(video)).name,
                    currency=CURRENCY_NON_CURRENT_DIAGNOSTIC,
                    non_current_reason=reasons,
                )
                steps["qc"] = {
                    "state": runtime.get("overall", "UNKNOWN"),
                    "receipts": [p.relative_to(project_dir).as_posix() for p in written],
                    "runtime": runtime,
                }
            except Exception as exc:  # noqa: BLE001
                steps["qc"] = {
                    "state": "BLOCKED",
                    "reason": redact_text(f"{type(exc).__name__}: {exc}"),
                }
        else:
            steps["qc"] = {"state": "NOT_RUN", "reason": "no composition output"}

    limitations.extend(
        [
            "fixture images and BGM are deterministic placeholders generated by this "
            "script; they are not third-party licensed media, and their receipts say so",
            "only the bundled SFX is genuine third-party material (Apache-2.0)",
            "no network or paid provider was called; an image requiring one is recorded "
            "as BLOCKED rather than fetched",
            "nothing here is production-ready; the manifest and receipts carry "
            "human_review=PENDING_FOUNDER_REVIEW",
        ]
    )

    _write_json(project_dir / "receipts" / "media-use-demo.json", report)

    required = ("status", "adopt", "import", "gate", "storyboard")
    blocked = [name for name in required if steps.get(name, {}).get("state") not in ("PASS",)]
    if steps.get("qc", {}).get("state") in ("BLOCKED", "FAIL"):
        blocked.append("qc")
    return _emit(report, EXIT_BLOCKED if blocked else EXIT_OK)


