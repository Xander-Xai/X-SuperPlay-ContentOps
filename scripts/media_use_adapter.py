#!/usr/bin/env python
"""Operator CLI for the pinned HyperFrames ``media-use`` integration.

This is the only command-line surface the integration adds. It exists so that
every adapter decision can be exercised from a terminal and recorded as a
receipt, rather than living only inside a test. It is deliberately a thin shell:
all policy lives in :mod:`contentops.media.media_use_adapter`.

Exit codes are stable and are part of the contract:

===== =======================================================================
0     the requested operation completed
1     an unexpected failure (I/O, invalid project state, unreadable record)
2     usage error (argparse)
5     BLOCKED: a decision a human must make, or a fail-closed refusal
===== =======================================================================

``5`` is not a bug. A missing network authorization, an unlicensed candidate or
an uninstalled skill are all *expected* outcomes of a fail-closed system, and a
caller needs to tell them apart from a crash.

Safety defaults: no network, no paid provider, no cross-project reuse, and no
provider forced. Each requires its own explicit flag.
"""

