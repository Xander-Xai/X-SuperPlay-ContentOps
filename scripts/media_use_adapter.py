def _common(parser: argparse.ArgumentParser, *, project: bool = True) -> None:
    parser.add_argument("--skill-dir", default=None, help="override the media-use skill directory")
    parser.add_argument("--node", default=None, help="node executable to use")
    parser.add_argument("--timeout", type=float, default=120.0, help="per-invocation timeout, 1..600s")
    if project:
        parser.add_argument("--project", default="projects/media-use-demo", help="project root")


def _auth_flags(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--allow-network", action="store_true", help="authorize network providers")
    parser.add_argument("--allow-paid", action="store_true", help="authorize a paid provider call")
    parser.add_argument("--budget", default=None, help="required with --allow-paid")
    parser.add_argument(
        "--allow-cross-project", action="store_true", help="authorize reuse from another project"
    )
    parser.add_argument(
        "--allowed-provider", action="append", default=[], help="provider permitted this run"
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="media_use_adapter",
        description="Pinned HyperFrames media-use integration (fail-closed by default).",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("status", help="report skill/node availability")
    _common(p)
    p.set_defaults(func=cmd_status)

    p = sub.add_parser("doctor", help="probe local dependencies")
    _common(p)
    p.set_defaults(func=cmd_doctor)

    p = sub.add_parser("candidates", help="list reusable assets without mutating anything")
    _common(p)
    p.add_argument("--type", required=True)
    p.add_argument("--intent", default="")
    p.add_argument("--global-cache", action="store_true")
    p.add_argument("--allow-cross-project", action="store_true")
    p.set_defaults(func=cmd_candidates)

    p = sub.add_parser("resolve", help="resolve one need, reusing local material first")
    _common(p)
    p.add_argument("--type", required=True)
    p.add_argument("--intent", default="")
    p.add_argument("--provider", default=None)
    _auth_flags(p)
    p.set_defaults(func=cmd_resolve)

    p = sub.add_parser("adopt", help="register files already under <project>/assets")
    _common(p)
    p.set_defaults(func=cmd_adopt)

    p = sub.add_parser("ingest", help="freeze a local file into the project inventory")
    _common(p)
    p.add_argument("--type", required=True)
    p.add_argument("--source", required=True)
    p.add_argument("--license", required=True)
    p.add_argument("--attribution", default="")
    p.add_argument("--rights-review", default="",
                   help="project-relative assets/<id>.rights.json for third-party ingest")
    p.set_defaults(func=cmd_ingest)

    p = sub.add_parser("import", help="turn a media-use record into a ContentOps asset")
    _common(p)
    p.add_argument("--type", required=True)
    p.add_argument("--record-id", default=None)
    p.add_argument("--record-file", default=None)
    p.add_argument("--license", default="")
    p.add_argument("--attribution", default="")
    p.add_argument("--rights-review", default="",
                   help="project-relative assets/<id>.rights.json for third-party imports")
    p.add_argument("--synthetic", action="store_true",
                   help="mark this import as generated/synthetic")
    p.add_argument("--role", default="visual_support")
    p.add_argument("--placement", default=None)
    p.add_argument("--asset-prefix", default="media-use")
    p.add_argument("--cross-project", action="store_true")
    p.set_defaults(func=cmd_import)

    p = sub.add_parser("verify", help="check an imported file and its receipt")
    _common(p)
    p.add_argument("--path", required=True, help="project-relative path")
    p.add_argument("--sha256", default=None)
    p.set_defaults(func=cmd_verify)

    p = sub.add_parser("demo", help="run the offline end-to-end integration sample")
    _common(p)
    p.add_argument("--skip-compose", action="store_true")
    p.set_defaults(func=cmd_demo)

    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.command == "import" and not (args.record_id or args.record_file):
        parser.error("import requires --record-id or --record-file")
    try:
        return int(args.func(args))
    except MediaUseError as exc:
        return _fail(exc)
    except FileNotFoundError as exc:
        return _fail(MediaUseError(CODE_CLI_FAILED, str(exc)))
    except Exception as exc:  # noqa: BLE001 - the CLI must report, not traceback
        return _fail(exc)


if __name__ == "__main__":
    sys.exit(main())
