# ---------------------------------------------------------------------------
# output helpers
# ---------------------------------------------------------------------------


def _emit(payload: Mapping[str, Any], code: int) -> int:
    print(json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=True))
    return code


def _fail(exc: Exception) -> int:
    if isinstance(exc, MediaUseError):
        code = EXIT_BLOCKED if exc.code in BLOCKED_CODES else EXIT_FAILURE
        return _emit(exc.as_dict(), code)
    return _emit(
        {
            "ok": False,
            "code": "UNEXPECTED_FAILURE",
            "message": redact_text(f"{type(exc).__name__}: {exc}"),
        },
        EXIT_FAILURE,
    )


def _ok(payload: Optional[Mapping[str, Any]] = None) -> Dict[str, Any]:
    body: Dict[str, Any] = {"ok": True}
    if payload:
        body.update(payload)
    return body


