@test
def test_the_child_is_argv_only_and_never_sees_a_credential():
    import contentops.media.media_use_adapter as module

    captured: Dict[str, Any] = {}
    original = module.hidden_run

    def recorder(cmd, **kwargs):
        captured.setdefault("calls", []).append({"cmd": list(cmd), "kwargs": dict(kwargs)})
        if list(cmd)[-1] == "--version":
            return subprocess.CompletedProcess(cmd, 0, "v20.11.0\n", "")
        if "--candidates" in cmd:
            return subprocess.CompletedProcess(cmd, 0, '{"ok":true,"candidates":[]}', "")
        return subprocess.CompletedProcess(cmd, 0, '{"ok":false,"error":"x"}', "")

    os.environ["MINIMAX_API_KEY"] = "super-secret-key"
    try:
        with tempfile.TemporaryDirectory() as raw:
            tmp = Path(raw)
            skill = _fake_skill(tmp)
            module.hidden_run = recorder
            try:
                adapter = MediaUseAdapter(skill_dir=skill, node="node", timeout=5)
                adapter.candidates("image", project_dir=_project(tmp))
            finally:
                module.hidden_run = original
    finally:
        os.environ.pop("MINIMAX_API_KEY", None)

    calls = captured["calls"]
    assert calls, "the CLI must have been invoked"
    for call in calls:
        assert isinstance(call["cmd"], list)
        assert all(isinstance(part, str) for part in call["cmd"])
        assert call["kwargs"].get("shell") in (None, False)
        env = call["kwargs"].get("env") or {}
        assert "MINIMAX_API_KEY" not in env
        assert not any("TOKEN" in key or "KEY" in key for key in env), env.keys()


