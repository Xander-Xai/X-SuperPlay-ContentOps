#!/usr/bin/env python3
"""Regression tests for the pinned HyperFrames ``media-use`` integration.

Run:
    python tests/test_media_use_adapter.py

**No provider request is made and no quota is spent.** The CLI-driving tests use
a fake skill whose ``resolve.mjs`` only prints a JSON file the test wrote. The
real skill, node and the network are never required for correctness: when node
is absent those tests are reported as SKIP, and the structured-unavailable path
is asserted instead.

What these tests are really about
---------------------------------
1. **Fail-closed by default.** No network, no paid call, no cross-project reuse,
   no forced provider. Each needs an explicit flag, and the refusal is a typed
   error rather than an empty success.
2. **Provenance is not upgradable.** A licensed import is never evidence
   capable, generated bytes are never importable as licensed external material,
   and no path outside the project can be imported.
3. **One asset list.** Imports feed the MediaManifest; this module never writes a
   second inventory.
"""

