@test
def test_the_manifest_is_byte_stable_for_the_same_state():
    with tempfile.TemporaryDirectory() as raw:
        tmp = Path(raw)
        project = _project(tmp)
        _write(project / "assets" / "pic.png")
        adapter = MediaUseAdapter(skill_dir=tmp / "absent", timeout=5)
        envelopes = []
        for index in range(3):
            path = project / "assets" / f"pic{index}.png"
            _write(path, f"bytes-{index}".encode())
            envelopes.append(
                adapter.import_record(
                    _record(f"assets/pic{index}.png", record_id=f"img_{index}"),
                    project_dir=project,
                    kind="image",
                    license="L",
                ).envelope
            )
        decisions = AssetQualityGate().evaluate_all(
            envelopes, repo_root=ROOT, project_root=project
        )
        first = build_manifest(envelopes, decisions)
        second = build_manifest(list(reversed(envelopes)), decisions)
        assert first.fingerprint() == second.fingerprint()
        assert first.as_dict() == second.as_dict()


