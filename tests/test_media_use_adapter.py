_FAKE_RESOLVE = r"""
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "responses");
const args = process.argv.slice(2);

function read(name) {
  return JSON.parse(readFileSync(join(root, name), "utf8"));
}

let payload;
if (args.includes("--doctor")) payload = read("doctor.json");
else if (args.includes("--candidates")) payload = read("candidates.json");
else if (args.includes("--adopt")) payload = read("adopt.json");
else if (args.includes("--ingest") || args.includes("--from")) payload = read("ingest.json");
else payload = read("resolve.json");

if (payload.__sleep_ms) {
  await new Promise((resolve) => setTimeout(resolve, payload.__sleep_ms));
}
if (payload.__exit_code) {
  console.error(payload.__stderr || "fake failure");
  process.exit(payload.__exit_code);
}
console.log(JSON.stringify(payload));
"""


def _fake_skill(tmp: Path, **responses: Dict[str, Any]) -> Path:
    skill = tmp / "skill"
    (skill / "scripts").mkdir(parents=True)
    (skill / "responses").mkdir()
    (skill / "SKILL.md").write_text("# fake media-use\n", encoding="utf-8")
    (skill / "scripts" / "resolve.mjs").write_text(_FAKE_RESOLVE, encoding="utf-8")
    defaults: Dict[str, Dict[str, Any]] = {
        "doctor.json": {"ok": True, "checks": []},
        "candidates.json": {"ok": True, "candidates": []},
        "adopt.json": {"ok": True, "assets": []},
        "ingest.json": {"ok": True},
        "resolve.json": {"ok": False, "error": "no provider"},
    }
    defaults.update({f"{name}.json": payload for name, payload in responses.items()})
    for name, payload in defaults.items():
        (skill / "responses" / name).write_text(json.dumps(payload), encoding="utf-8")
    return skill


class _FixtureAdapter(MediaUseAdapter):
    """Exercise the process protocol using only the generated fake skill.

    This subclass exists exclusively in the test file. It does not establish
    production dependency trust or demonstrate that the real CLI is usable.
    """

    def _require_trusted_runtime(self):
        from contentops.media.media_use_adapter import MediaUseRuntime, STATE_TRUSTED_RUNTIME

        return MediaUseRuntime(
            state=STATE_TRUSTED_RUNTIME,
            root=self.skill_dir,
            entry=self.resolve_script,
            node=Path(shutil.which("node") or "node"),
            verb_prefix=(),
        )

    @classmethod
    def _cli_args(cls, args):
        return [str(arg) for arg in args]

    def require_available(self):
        return self.status()


def _adapter(tmp: Path, **responses: Dict[str, Any]) -> MediaUseAdapter:
    node = _require_node()
    return _FixtureAdapter(skill_dir=_fake_skill(tmp, **responses), node=node, timeout=10)


def _project(tmp: Path) -> Path:
    project = tmp / "project"
    (project / "assets").mkdir(parents=True)
    return project


def _write(path: Path, data: bytes = b"fake-media-bytes") -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return path


def _record(path: str, kind: str = "image", record_id: str = "img_001") -> Dict[str, Any]:
    return {
        "id": record_id,
        "type": kind,
        "path": path,
        "source": "existing",
        "description": "test fixture",
    }


def _expect(code: str, fn) -> MediaUseError:
    try:
        fn()
    except MediaUseError as exc:
        assert exc.code == code, f"expected {code}, got {exc.code}: {exc}"
        return exc
    raise AssertionError(f"expected MediaUseError {code}, nothing was raised")


